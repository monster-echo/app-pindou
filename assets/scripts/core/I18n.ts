export type I18nKey = keyof typeof DICT['zh'];

export function getLang(): LangCode {
    return SaveManager.ins.language;
}

export function t(key: I18nKey, ...args: Array<string | number>): string {
    const lang = SaveManager.ins.language;
    const raw = (DICT[lang] && DICT[lang][key]) || DICT.zh[key] || String(key);
    return raw.replace(/\{(\d+)\}/g, (_m, idxStr) => {
        const idx = Number(idxStr);
        return args[idx] !== undefined ? String(args[idx]) : '';
    });
}

export function levelName(lv: LevelData): string {
    return SaveManager.ins.language === 'en' && lv.nameEn ? lv.nameEn : lv.name;
}
